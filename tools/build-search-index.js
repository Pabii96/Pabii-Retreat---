/* Builds js/search-index.js from every HTML page so the site search
   can find content on ALL pages. Run:  node tools/build-search-index.js */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const pages = fs.readdirSync(root).filter(f => f.endsWith('.html'));
const strip = s => s.replace(/<script[\s\S]*?<\/script>/gi, ' ')
  .replace(/<!--[\s\S]*?-->/g, ' ').replace(/<[^>]+>/g, ' ')
  .replace(/&copy;/g, '©').replace(/&amp;/g, '&').replace(/&#39;|&apos;/g, "'")
  .replace(/&[a-z#0-9]+;/gi, ' ').replace(/\s+/g, ' ').trim();
const index = [];
for (const file of pages) {
  const html = fs.readFileSync(path.join(root, file), 'utf8');
  const title = strip((html.match(/<title>([\s\S]*?)<\/title>/i) || [, file])[1]).split('|')[0].trim();
  const main = (html.match(/<main[\s\S]*?<\/main>/i) || [html])[0];
  // one entry per <section> so results point at the right part of the page
  const sections = main.match(/<section[\s\S]*?<\/section>/gi) || [main];
  sections.forEach((sec, i) => {
    const heading = strip((sec.match(/<h2[^>]*>([\s\S]*?)<\/h2>/i) || [, title])[1]);
    const alts = [...sec.matchAll(/alt="([^"]*)"/g)].map(m => m[1]).join(' ');
    index.push({ page: title, url: file, heading, text: strip(sec) + ' ' + alts });
  });
}
fs.writeFileSync(path.join(root, 'js', 'search-index.js'),
  '/* AUTO-GENERATED by tools/build-search-index.js - do not edit by hand */\nwindow.SITE_SEARCH_INDEX = ' +
  JSON.stringify(index, null, 1) + ';\n');
console.log('Indexed', index.length, 'sections from', pages.length, 'pages');
